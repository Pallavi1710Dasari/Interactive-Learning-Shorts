def test_mascot_prompt_built_once_and_cache_reused_across_reels():
    """
    The cta entry's prompt is style.mascot_prompt() — identical text
    regardless of reel — so a second reel's cta call is a cache hit, not a
    second real call.

    Checks "reel_b triggers NO ADDITIONAL provider call beyond whatever
    reel_a triggered" rather than "exactly 1 call total" — output/.image_cache/
    persists on disk across test runs (by design: that's the whole point of
    a cache), so a prior run of this exact test may have already cached
    mascot_prompt()'s image, making reel_a ITSELF a hit too (0 calls, not 1).
    Either way, the invariant that actually matters — reel_b never adds a
    2nd real call on top of reel_a's — holds regardless of that history.
    """
    from shorts import style
    calls = []
    original = imagegen.StubImageProvider.generate
    imagegen.StubImageProvider.generate = lambda self, *a, **kw: (calls.append(1), original(self, *a, **kw))[1]
    try:
        imagegen.generate_bytes("reel_a", "cta", style.mascot_prompt(),
                               provider=imagegen.StubImageProvider())
        after_a = len(calls)
        imagegen.generate_bytes("reel_b", "cta", style.mascot_prompt(),
                               provider=imagegen.StubImageProvider())
        after_b = len(calls)
    finally:
        imagegen.StubImageProvider.generate = original
    assert after_a <= 1 and after_b == after_a, (after_a, after_b)
    print(f"   ok — two different reels' cta calls, same mascot prompt, "
         f"share one cache entry — reel_b added zero additional real calls "
         f"(calls so far: {after_a})")


# ========================================================== refs + setting ref

class _RecordingProvider(imagegen.StubImageProvider):
    """Records the refs list every generate() call received, so a test can
    check ordering/setting-ref-augmentation without inspecting pixels.

    OWN `name`, distinct from "stub" — the cache key is sha256(provider.name
    + model + prompt + ...), so sharing StubImageProvider's plain "stub" name
    would let a cache entry written by any OTHER test's plain StubImageProvider
    (identical prompt+refs+seed) silently serve this one from cache, and
    generate() would never be called at all — nothing to record, and a false
    pass/fail depending on test execution order and leftover .image_cache/
    state from earlier runs."""
    name = "stub_recording"

    def __init__(self):
        self.calls = []

    def generate(self, prompt, refs=None, size=imagegen.FRAME_SIZE, seed=None, shot_id=""):
        self.calls.append({"shot_id": shot_id, "refs": list(refs or [])})
        return super().generate(prompt, refs=refs, size=size, seed=seed, shot_id=shot_id)


def test_refs_order_matches_reference_image_n_in_the_prompt():
    _clean_reel_output("stub_e2e_refs")
    story = _load_story()
    two_char_shot = next(s for s in story.shots if s.kind == "scene" and len(s.characters) == 2)
    prompt = build_shot_prompt(two_char_shot, story)

    # Parse "reference image N" against each named character, in the order
    # the PROMPT names them (not shot.characters — the prompt is the
    # contract a real provider actually reads).
    named_in_order = re.findall(r"^(\w+): .*matching reference image (\d+)", prompt, re.M)
    assert [n for n, _ in named_in_order] == two_char_shot.characters
    assert [i for _, i in named_in_order] == ["1", "2"]

    provider = _RecordingProvider()
    refs = cast_refs_for_shot(two_char_shot)
    imagegen.generate_bytes("stub_e2e_refs", two_char_shot.shot_id, prompt,
                            refs=refs, provider=provider)
    got_refs = provider.calls[0]["refs"]
    assert [r.stem for r in got_refs] == [c.lower() for c in two_char_shot.characters]
    print(f"   ok — the prompt's 'reference image 1/2' order "
         f"({[n for n, _ in named_in_order]}) matches the refs list actually "
         f"passed to the provider ({[r.name for r in got_refs]})")


def test_first_wide_frame_becomes_setting_ref_for_later_shots():
    """
    Drives the SAME logic story_frames.run() uses (render the first wide
    shot, then pass its path as an extra ref to every later shot) directly
    against a _RecordingProvider, so the refs each call actually received
    can be inspected — run() itself always asks imagegen.select_provider()
    for a fresh provider internally, which would hide that from a test
    calling run() as a black box.
    """
    _clean_reel_output("stub_e2e_setting")
    story = _load_story()
    provider = _RecordingProvider()
    shots = story_frames.select_sample(story_frames._scene_shots(story), 3)

    wide = next(s for s in shots if s.framing == "wide")
    others = [s for s in shots if s.shot_id != wide.shot_id]
    wide_path = imagegen.render_frame("stub_e2e_setting", wide.shot_id,
                                      build_shot_prompt(wide, story),
                                      refs=cast_refs_for_shot(wide), provider=provider)
    for s in others:
        refs = cast_refs_for_shot(s) + [wide_path]
        imagegen.generate_bytes("stub_e2e_setting", s.shot_id, build_shot_prompt(s, story),
                                refs=refs, provider=provider)

    later_calls = [c for c in provider.calls if c["shot_id"] != wide.shot_id]
    assert later_calls, "need at least one non-wide shot in the sample to check this"
    for c in later_calls:
        assert wide_path in c["refs"], (c["shot_id"], c["refs"])
    print(f"   ok — every shot after the first wide one carries {wide_path.name} "
         f"as an extra (setting) reference")


