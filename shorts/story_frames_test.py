STORY_PATH = config.OUTPUT_DIR / "stub_e2e.story.json"


def _ensure_stub_story():
    """
    output/stub_e2e.story.json is written by story_mode_test.py's own
    test_full_story_path_runs_end_to_end_under_stub. Generate it here too
    (idempotent, free under SHORTS_STUB=1) so this file can run standalone
    without depending on test execution order across files.
    """
    if STORY_PATH.exists():
        return
    import shorts.story_mode_test as smt
    smt.test_full_story_path_runs_end_to_end_under_stub()


def _load_story():
    from shorts.schema import StoryScript
    return StoryScript.model_validate_json(STORY_PATH.read_text(encoding="utf-8"))


def _approve_full_cast():
    shutil.rmtree(cast_sheets.ASSETS_DIR, ignore_errors=True)
    shutil.rmtree(cast_sheets.CANDIDATES_DIR, ignore_errors=True)
    for name in cast_sheets.CAST_ORDER:
        cast_sheets.main(["--candidates", "1", "--character", name.lower(), "--yes"])
        cast_sheets.main(["--approve", name.lower(), "1"])


def _clean_reel_output(short_id: str):
    shutil.rmtree(config.OUTPUT_DIR / short_id, ignore_errors=True)
    imagegen.reset_call_count(short_id)


def _dedicated_short_id(short_id: str) -> None:
    """
    story_frames.main() reads output/<short_id>.story.json, keyed by the
    exact short_id argv[0] — a test that wants its OWN output directory
    (rather than sharing "stub_e2e" with every other test in this file)
    needs a matching story file under that name too, not just a clean
    output dir. Copies the shared stub story once under the new name.
    """
    _clean_reel_output(short_id)
    dst = config.OUTPUT_DIR / f"{short_id}.story.json"
    if not dst.exists():
        dst.write_text(STORY_PATH.read_text(encoding="utf-8"), encoding="utf-8")


def _run(argv):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        code = story_frames.main(argv)
    return code, buf.getvalue()


# Every shot's prompt is DETERMINISTIC (see test_build_shot_prompt_is_
# deterministic below) — the same fixed stub story, run twice, asks for the
# exact same prompts every time. That's the point (it's what makes a real
# provider's cache work at all), but it means output/.image_cache/ from a
# PREVIOUS run of this exact file would make every "was the provider called"
# check below a false negative on run 2 onward. Cleared once, here, so this
# file's own monkeypatched-call-counting tests start from a clean cache
# regardless of what an earlier run left behind — the cache itself is
# disposable, regenerable content, never anything worth preserving.
shutil.rmtree(config.OUTPUT_DIR / ".image_cache", ignore_errors=True)

_ensure_stub_story()
_approve_full_cast()


