def test_judge_fail_then_pass_regenerates_with_fix_text_and_new_seed():
    """
    RESTYLE_TO_STORY_REELS.md Step 6 Part 3, verbatim: 'On fail: append the
    judge's reasons as "FIX: ..." to the prompt, use a new seed, regenerate.'
    A recording fake provider proves both halves of that sentence actually
    happened, not just that the shot eventually passed.
    """
    _clean_reel_output("stub_e2e_judge_regen")
    shot, story = _fresh_shot()

    class _RecordingStub(imagegen.StubImageProvider):
        name = "stub_judge_regen_record"   # own cache namespace — see Step 5's
                                           # test file note on why this matters
        def __init__(self):
            self.calls = []
        def generate(self, prompt, refs=None, size=imagegen.FRAME_SIZE, seed=None, shot_id=""):
            self.calls.append({"prompt": prompt, "seed": seed})
            return super().generate(prompt, refs=refs, size=size, seed=seed, shot_id=shot_id)

    provider = _RecordingStub()
    verdicts = [
        _judge(character_match=2, reasons=["hair color does not match the reference"]),
        _judge(),   # clean pass
    ]
    calls = {"n": 0}

    def fake_judge(*a, **kw):
        v = verdicts[calls["n"]]
        calls["n"] += 1
        return v

    original = story_frames.judge_story_frame
    story_frames.judge_story_frame = fake_judge
    try:
        result = story_frames.render_shot_with_judge(
            "stub_e2e_judge_regen", shot, build_shot_prompt(shot, story),
            cast_refs_for_shot(shot), None, provider, no_judge=False)
    finally:
        story_frames.judge_story_frame = original

    assert result["final_status"] == "PASS"
    assert len(result["attempts"]) == 2
    assert len(provider.calls) == 2
    assert provider.calls[0]["seed"] is None
    assert provider.calls[1]["seed"] == 2, provider.calls[1]["seed"]
    assert "FIX:" in provider.calls[1]["prompt"]
    assert "hair color does not match the reference" in provider.calls[1]["prompt"]
    print(f"   ok — a failing judge verdict regenerates with the reasons "
         f"appended as 'FIX: ...' and a new seed ({provider.calls[1]['seed']}), "
         f"then passes on attempt 2")


def test_exhausted_attempts_marks_needs_review_and_keeps_best_scoring():
    """
    Both attempts fail (STORY_FRAME_ATTEMPTS defaults to 2), with DIFFERENT
    judge totals — proves "keep the best attempt" means the higher-scoring
    one's actual pixels end up at final_path, not just whichever ran last.
    """
    _clean_reel_output("stub_e2e_exhaust")
    shot, story = _fresh_shot()

    class _RecordingStub(imagegen.StubImageProvider):
        name = "stub_exhaust_record"
        def __init__(self):
            self.frames = []
        def generate(self, prompt, refs=None, size=imagegen.FRAME_SIZE, seed=None, shot_id=""):
            raw = super().generate(prompt, refs=refs, size=size, seed=seed, shot_id=shot_id)
            self.frames.append(raw)
            return raw

    provider = _RecordingStub()
    # attempt 1 scores HIGHER (22) than attempt 2 (21) — both still fail
    # (character_match < 3 either way), so attempt 1 is the one that must
    # survive as final_path's actual content.
    verdicts = [
        _judge(character_match=2, reasons=["attempt 1: still a bit off"]),      # total 22
        _judge(character_match=1, reasons=["attempt 2: worse, not better"]),   # total 21
    ]
    calls = {"n": 0}

    def fake_judge(*a, **kw):
        v = verdicts[calls["n"]]
        calls["n"] += 1
        return v

    original = story_frames.judge_story_frame
    story_frames.judge_story_frame = fake_judge
    try:
        result = story_frames.render_shot_with_judge(
            "stub_e2e_exhaust", shot, build_shot_prompt(shot, story),
            cast_refs_for_shot(shot), None, provider, no_judge=False)
    finally:
        story_frames.judge_story_frame = original

    assert result["final_status"] == "NEEDS_REVIEW"
    assert len(result["attempts"]) == 2
    assert [a["status"] for a in result["attempts"]] == ["FAIL", "FAIL"]
    final_bytes = Path(result["final_path"]).read_bytes()
    assert final_bytes == provider.frames[0], (
        "final_path's actual pixels must be attempt 1's (higher total, 22), "
        "not attempt 2's (21) even though attempt 2 ran last and would "
        "otherwise be what's left on disk")
    print(f"   ok — both attempts fail -> NEEDS_REVIEW, and final_path's "
         f"actual bytes are the BEST-scoring attempt's (attempt 1, total 22), "
         f"not just the last one written")


