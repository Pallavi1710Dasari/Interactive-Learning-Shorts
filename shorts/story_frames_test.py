def test_run_reuses_an_image_across_matching_shots_and_copies_the_same_bytes():
    _clean_reel_output("stub_e2e_reuse")
    story = _load_story()
    # Two shots engineered to share a reuse key (same characters/framing/
    # emotion/key_prop, different camera), inserted into a real story's shot
    # list so run()'s full pipeline (budget, judge, etc.) exercises them.
    base = next(s for s in story_frames._scene_shots(story) if s.story_beat != "reaction")
    twin = base.model_copy(update={
        "shot_id": f"{base.shot_id}_twin",
        "camera": "push_left" if base.camera != "push_left" else "push_right",
    })
    # Spliced in RIGHT AFTER `base`, not appended at the end — the epoch is
    # computed from story.shots' own chronological order (_reveal_epochs),
    # so a twin appended after this story's own later reveals would land in
    # a LATER epoch than `base` and correctly never reuse it; this test is
    # about same-epoch reuse, so it needs the two adjacent.
    idx = story.shots.index(base)
    story.shots = story.shots[:idx + 1] + [twin] + story.shots[idx + 1:]
    (config.OUTPUT_DIR / "stub_e2e_reuse.story.json").write_text(
        story.model_dump_json(indent=2), encoding="utf-8")

    code, out = _run(["stub_e2e_reuse", "--all", "--yes", "--no-judge"])
    assert code == 0, out
    assert f"REUSED from {base.shot_id}" in out, out
    data = json.loads(story_frames._judge_path("stub_e2e_reuse").read_text())
    assert data[twin.shot_id]["reused_from"] == base.shot_id

    base_bytes = (config.OUTPUT_DIR / "stub_e2e_reuse" / "frames" /
                 f"shot_{base.shot_id}.png").read_bytes()
    twin_bytes = (config.OUTPUT_DIR / "stub_e2e_reuse" / "frames" /
                 f"shot_{twin.shot_id}.png").read_bytes()
    assert base_bytes == twin_bytes, "a reused shot's file must be a byte-for-byte copy"
    print(f"   ok — a shot sharing {base.shot_id}'s characters/framing/"
         f"emotion/key_prop (different camera: {base.camera!r} vs "
         f"{twin.camera!r}) reuses its image — {twin.shot_id}'s own frame "
         f"file is a byte-for-byte copy, no provider call spent on it")


